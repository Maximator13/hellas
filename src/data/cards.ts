function ancient(author: string, work: string, locus?: string): Source {
  return locus === undefined ? { kind: 'ancient', author, work } : { kind: 'ancient', author, work, locus }
}

function modern(author: string, work: string): Source {
  return { kind: 'modern', author, work }
}

